import type { ReportStatusEvent, TimelineEventKind } from "./report";

/**
 * Which timeline entries residents may see.
 *
 * - A resident's (non-example) case shows status changes only ("Recibido", "En revisión", …).
 *   Every AI, referral, pipeline or office step is private to moderators (the audit log).
 * - An example case also shows the pipeline's moderator-approved steps ("Referral prepared –
 *   sending is paused in this demo", follow-up updates, the simulated office's steps), so the
 *   demo can show the whole loop.
 * - The earlier pipeline's automatic entries (before 2026-10: "the AI reviewed this report", "the
 *   AI prepared a referral to {office}", "waiting for approval", and its approve/decline lines)
 *   are never public on any case: they weren't moderator-approved, and some named a real office.
 *
 * Applied twice: when a case is turned into a PublicCase (toPublicCase), and when a step is
 * written (the stores don't write a public entry the rule would hide). Migration 0009 moved the
 * entries this rule hides into the audit log.
 */
export const LEGACY_PRIVATE_KINDS: ReadonlySet<TimelineEventKind> = new Set([
  "ai_reviewed",
  "referral_prepared",
  "awaiting_approval",
  "referral_approved",
  "referral_declined",
]);

export function isPublicTimelineEvent(
  event: Pick<ReportStatusEvent, "kind">,
  sourceType: "community" | "demonstration",
): boolean {
  const kind = event.kind ?? "status";
  if (kind === "status") return true;
  if (sourceType !== "demonstration") return false;
  return !LEGACY_PRIVATE_KINDS.has(kind);
}

const kindList = (kinds: Iterable<string>) => [...kinds].map((k) => `'${k}'`).join(", ");

/**
 * SQL: moves every timeline entry the rule hides into the private audit log (keeping when it
 * happened, who did it, the office id and any note), then removes it from the public timeline.
 * Nothing is lost. `limitToCases` restricts it to a `$1::text[]` of case numbers.
 */
export function movePrivateTimelineStatements(limitToCases = false): [insert: string, remove: string] {
  const hidden = `e.kind is not null and e.kind <> 'status'
      and (c.source_type <> 'demonstration' or e.kind in (${kindList(LEGACY_PRIVATE_KINDS)}))${limitToCases ? "\n      and c.case_number = any($1::text[])" : ""}`;
  const insert = `insert into public.agent_audit (case_number, community_id, occurred_at, actor_type, actor, action, summary)
select c.case_number, c.community_id, e.occurred_at,
  case e.actor_type when 'agent' then 'agent' when 'office' then 'office' when 'moderator' then 'moderator' else 'system' end,
  case e.actor_type when 'agent' then 'CommonGround AI (earlier pipeline)' when 'moderator' then 'moderator' when 'office' then 'office' else 'system' end,
  'timeline_made_private',
  'Earlier public timeline entry, now private: ' || e.kind || ' (status ' || e.status || ')'
    || coalesce(' — office: ' || e.contact_id, '')
    || coalesce(' — note: ' || coalesce(e.note_es, e.note), '')
from public.case_events e
join public.cases c on c.id = e.case_id
where ${hidden}`;
  const remove = `delete from public.case_events e
using public.cases c
where c.id = e.case_id and ${hidden}`;
  return [insert, remove];
}

/** The same, as one SQL script (no parameters). */
export function movePrivateTimelineSql(): string {
  return movePrivateTimelineStatements(false).join(";\n\n") + ";\n";
}

/** db/migrations/0009_private_timeline_entries.sql. */
export function buildPrivateTimelineMigrationSql(): string {
  return `-- CommonGround: make earlier AI/referral timeline entries private (moved to the audit log).
--
-- GENERATED by src/lib/schema/public-timeline.ts — don't edit by hand. Regenerate with:
-- npx vitest run src/lib/store/__tests__/db-sql.test.ts -u
--
-- Residents' cases show status changes only; example cases also show the pipeline's
-- moderator-approved steps; the earlier pipeline's automatic entries are public on no case.
-- Every entry this hides is copied into agent_audit first (time, actor, kind, office id, note),
-- then removed from the public timeline. Nothing is lost. Safe to run twice.

${movePrivateTimelineSql()}`;
}
